import type {
  CreateReplyBody,
  CreateTweetBody,
  Page,
  PageQuery,
  Tweet,
  TweetAncestors,
} from '@chirp/shared';
import { THREAD_ANCESTORS_MAX } from '@chirp/shared';
import type { FastifyBaseLogger } from 'fastify';

import type { PrismaClient } from '../../generated/prisma/client';
import { decodeCursor, keysetAfterOldestFirst, oldestFirst, toPage } from '../../lib/cursor';
import { ForbiddenError, NotFoundError, ValidationError } from '../../lib/errors';
import { isForeignKeyViolation, isUniqueViolation } from '../../lib/prisma-errors';
import { toTweet, tweetRowSelect } from '../../lib/serializers';
import type { StorageService } from '../../lib/storage';
import { notifyReply } from '../notifications/rules';

export interface TweetsServiceDependencies {
  prisma: PrismaClient;
  storage: StorageService;
  /** Records failures that must not fail the request (an image left behind on delete). */
  log: Pick<FastifyBaseLogger, 'warn'>;
}

export type TweetsService = ReturnType<typeof createTweetsService>;

/** The chirp a reply answers; its author receives the reply notification (ADR-15). */
interface ParentTweet {
  id: string;
  authorId: string;
}

const UNUSABLE_IMAGE = 'This image can’t be used. Upload it again.';

function unusableImage(cause?: unknown): ValidationError {
  return new ValidationError(UNUSABLE_IMAGE, {
    fieldErrors: { imageKey: [UNUSABLE_IMAGE] },
    cause,
  });
}

export function createTweetsService({ prisma, storage, log }: TweetsServiceDependencies) {
  const publicUrl = (key: string) => storage.publicUrl(key);

  /**
   * An image must be the author's own chirp upload (ADR-14: keys are `users/{id}/tweet/…`,
   * generated by the API) and must have arrived in storage. Someone else's key and a key that
   * was never uploaded get the same answer, so keys reveal nothing.
   */
  async function checkImage(authorId: string, imageKey: string): Promise<void> {
    if (!imageKey.startsWith(`users/${authorId}/tweet/`)) throw unusableImage();
    if (!(await storage.exists(imageKey))) throw unusableImage();
  }

  /** Top-level chirps and replies share every rule but the parent (ADR-24). */
  async function insert(
    authorId: string,
    { content, imageKey }: CreateTweetBody,
    parent?: ParentTweet,
  ): Promise<Tweet> {
    if (imageKey !== undefined) await checkImage(authorId, imageKey);
    try {
      const tweet = await prisma.$transaction(async (tx) => {
        const created = await tx.tweet.create({
          data: { authorId, content, imageKey, parentId: parent?.id },
          select: tweetRowSelect(authorId),
        });
        if (parent !== undefined) {
          await notifyReply(tx, {
            replyId: created.id,
            replierId: authorId,
            parentAuthorId: parent.authorId,
          });
        }
        return created;
      });
      return toTweet(tweet, publicUrl);
    } catch (error) {
      // The image is already on another chirp: sharing it would let one delete remove both.
      if (isUniqueViolation(error)) throw unusableImage(error);
      // The parent was deleted between the lookup and the insert.
      if (parent !== undefined && isForeignKeyViolation(error)) {
        throw new NotFoundError('Tweet', { cause: error });
      }
      throw error;
    }
  }

  async function create(authorId: string, body: CreateTweetBody): Promise<Tweet> {
    return insert(authorId, body);
  }

  /** A reply to any chirp, replies included, so conversations can nest (ADR-24). */
  async function reply(authorId: string, parentId: string, body: CreateReplyBody): Promise<Tweet> {
    return insert(authorId, body, await findExisting(parentId));
  }

  async function findExisting(id: string): Promise<ParentTweet> {
    const tweet = await prisma.tweet.findUnique({
      where: { id },
      select: { id: true, authorId: true },
    });
    if (!tweet) throw new NotFoundError('Tweet');
    return tweet;
  }

  async function ensureExists(id: string): Promise<void> {
    await findExisting(id);
  }

  /** Direct replies only, oldest first, so a conversation reads top-down (ADR-24). */
  async function replies(
    id: string,
    viewerId: string,
    { cursor, limit }: PageQuery,
  ): Promise<Page<Tweet>> {
    // Decoded first, so a bad cursor is a 400 whether or not the chirp exists.
    const after = cursor === undefined ? undefined : decodeCursor(cursor);
    await ensureExists(id);

    const rows = await prisma.tweet.findMany({
      where: { AND: [{ parentId: id }, keysetAfterOldestFirst(after)] },
      orderBy: oldestFirst,
      take: limit + 1,
      select: tweetRowSelect(viewerId),
    });
    return toPage(rows, limit, (row) => toTweet(row, publicUrl));
  }

  /**
   * The chirps above this one, root first. A recursive query walks up `parent_id`; it stops at
   * the nearest `THREAD_ANCESTORS_MAX`, so the first item's `replyTo` still points further up
   * when the thread is deeper.
   */
  async function ancestors(id: string, viewerId: string): Promise<TweetAncestors> {
    await ensureExists(id);

    const chain = await prisma.$queryRaw<Array<{ id: string; depth: number }>>`
      WITH RECURSIVE chain (id, parent_id, depth) AS (
        SELECT parent.id, parent.parent_id, 1
        FROM tweets AS child
        JOIN tweets AS parent ON parent.id = child.parent_id
        WHERE child.id = ${id}::uuid
        UNION ALL
        SELECT parent.id, parent.parent_id, chain.depth + 1
        FROM chain
        JOIN tweets AS parent ON parent.id = chain.parent_id
        WHERE chain.depth < ${THREAD_ANCESTORS_MAX}
      )
      SELECT id, depth FROM chain`;
    if (chain.length === 0) return { items: [] };

    const rows = await prisma.tweet.findMany({
      where: { id: { in: chain.map((row) => row.id) } },
      select: tweetRowSelect(viewerId),
    });
    const depthOf = new Map(chain.map((row) => [row.id, row.depth]));
    // A chirp deleted between the two queries simply drops out of the chain.
    const rootFirst = rows.sort((a, b) => (depthOf.get(b.id) ?? 0) - (depthOf.get(a.id) ?? 0));
    return { items: rootFirst.map((row) => toTweet(row, publicUrl)) };
  }

  async function get(id: string, viewerId: string): Promise<Tweet> {
    const tweet = await prisma.tweet.findUnique({
      where: { id },
      select: tweetRowSelect(viewerId),
    });
    if (!tweet) throw new NotFoundError('Tweet');
    return toTweet(tweet, publicUrl);
  }

  /**
   * Only the author may delete a tweet; a missing tweet is reported before ownership. Its
   * replies cascade in the database (ADR-24); their images are left behind like any orphan
   * upload (ADR-14).
   */
  async function remove(id: string, userId: string): Promise<void> {
    const tweet = await prisma.tweet.findUnique({
      where: { id },
      select: { authorId: true, imageKey: true },
    });
    if (!tweet) throw new NotFoundError('Tweet');
    if (tweet.authorId !== userId) throw new ForbiddenError('You can only delete your own chirps');

    // deleteMany tolerates a concurrent delete of the same tweet instead of throwing P2025.
    await prisma.tweet.deleteMany({ where: { id, authorId: userId } });

    // Best effort: the chirp is gone either way; a leftover object is only wasted space (ADR-14).
    if (tweet.imageKey !== null) {
      try {
        await storage.delete(tweet.imageKey);
      } catch (error) {
        log.warn(
          { err: error, key: tweet.imageKey },
          'Could not delete the image of a deleted chirp',
        );
      }
    }
  }

  return { create, reply, replies, ancestors, get, remove };
}
